function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(file));
    else if (e.isFile() && e.name.endsWith('.html')) out.push(file);
  }
  return out;
}

