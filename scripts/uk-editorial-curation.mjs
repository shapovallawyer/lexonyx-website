function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(file));
    else if (entry.isFile() && entry.name.endsWith('.html')) out.push(file);
  }
  return out;
}

function englishAlternate(html) {
  const m = html.match(/<link\b[^>]*rel=["']alternate["'][^>]*hreflang=["']en["'][^>]*href=["']([^"']+)["'][^>]*>/i)
    || html.match(/<link\b[^>]*hreflang=["']en["'][^>]*href=["']([^"']+)["'][^>]*rel=["']alternate["'][^>]*>/i)
    || html.match(/<link\b[^>]*href=["']([^"']+)["'][^>]*hreflang=["']en["'][^>]*rel=["']alternate["'][^>]*>/i);
  return m ? m[1] : null;
}

function normaliseHead(html, rel) {
  let out = html;
  out = out.replace(/"inLanguage"\s*:\s*"ru"/g, '"inLanguage":"uk"');

  const en = englishAlternate(out);
  if (en) {
    out = out.replace(/<link\b[^>]*rel=["']alternate["'][^>]*hreflang=["']x-default["'][^>]*>/gi,
      `<link rel="alternate" hreflang="x-default" href="${en}" />`);
    out = out.replace(/<link\b[^>]*hreflang=["']x-default["'][^>]*rel=["']alternate["'][^>]*>/gi,
      `<link rel="alternate" hreflang="x-default" href="${en}" />`);
  }

  if (rel === 'uk/index.html') {
    out = out.replace(/\n\s*<script type=["']application\/ld\+json["']>\s*\{[\s\S]*?"@type"\s*:\s*"WebSite"[\s\S]*?"SearchAction"[\s\S]*?<\/script>/i, '');
  }

  const visualHref = '/uk/visual-fixes.css?v=20260819';
  if (!out.includes(visualHref) && /<\/head>/i.test(out)) {
    out = out.replace(/<\/head>/i, `  <link rel="stylesheet" href="${visualHref}" />\n</head>`);
  }

  return out;
}

let scanned = 0;
let changed = 0;
for (const file of walk(UK)) {
  const rel = path.relative(ROOT, file).replaceAll('\\', '/');
  const before = fs.readFileSync(file, 'utf8');
  let after = before;
  for (const [from, to] of replacements) after = after.split(from).join(to);
  for (const [from, to] of (pageSpecific[rel] || [])) after = after.split(from).join(to);
  after = normaliseHead(after, rel);

  if (after !== before) {
    fs.writeFileSync(file, after, 'utf8');
    changed++;
  }
  scanned++;
}

