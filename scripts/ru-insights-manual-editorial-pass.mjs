function applyPairs(text, pairs) {
  let out = text;
  for (const [from, to] of pairs) out = out.split(from).join(to);
  return out
    .replace(/([А-ЯЁ])([А-ЯЁ])(?=[а-яё])/g, (_, a, b) => a + b.toLowerCase())
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+([,.;:!?])/g, '$1');
}

function editJsonLd(html, pairs) {
  return html.replace(/(<script\b[^>]*type=["']application\/ld\+json["'][^>]*>)([\s\S]*?)(<\/script>)/gi, (all, open, body, close) => {
    try {
      const data = JSON.parse(body);
      const walk = value => {
        if (Array.isArray(value)) return value.map(walk);
        if (value && typeof value === 'object') {
          for (const key of Object.keys(value)) value[key] = walk(value[key]);
          return value;
        }
        if (typeof value === 'string' && !/^https?:\/\//i.test(value)) return applyPairs(value, pairs);
        return value;
      };
      return open + JSON.stringify(walk(data), null, 2) + close;
    } catch {
      return all;
    }
  });
}

function setSeo(html, cfg) {
  if (!cfg) return html;
  html = html.replace(/<title>[\s\S]*?<\/title>/i, `<title>${cfg.title}</title>`);
  html = html.replace(/(<meta\b[^>]*name=["']description["'][^>]*content=["'])[^"']*(["'][^>]*>)/i, `$1${cfg.description}$2`);
  html = html.replace(/(<meta\b[^>]*property=["']og:title["'][^>]*content=["'])[^"']*(["'][^>]*>)/i, `$1${cfg.title}$2`);
  html = html.replace(/(<meta\b[^>]*property=["']og:description["'][^>]*content=["'])[^"']*(["'][^>]*>)/i, `$1${cfg.description}$2`);
  html = html.replace(/(<meta\b[^>]*name=["']twitter:title["'][^>]*content=["'])[^"']*(["'][^>]*>)/i, `$1${cfg.title}$2`);
  html = html.replace(/(<meta\b[^>]*name=["']twitter:description["'][^>]*content=["'])[^"']*(["'][^>]*>)/i, `$1${cfg.description}$2`);
  return html;
}

