function cleanHtml(html, rel) {
  let out = html;
  for (const [from, to] of replacements) out = out.split(from).join(to);

  out = out.replace(/<div\b[^>]*class=["'][^"']*badge[^"']*["'][^>]*>[\s\S]*?(?:С|C)\s*2012\s*(?:ГОДА|года)[\s\S]*?<\/div>/gi, '');
  out = out.replace(/(?:С|C)\s*2012\s*(?:ГОДА|года)/g, '');

  if (rel === 'ru/zaprosit-razbor.html') {
    const hero = `<p class="section-subtitle">
          Короткая форма, чтобы описать задачу и выбрать подходящий формат работы:
          <strong>экспресс-проверка рисков</strong>, <strong>банковская готовность</strong>,
          <strong>НДС / OSS / IOSS</strong> или <strong>сопровождение</strong>.
        </p>`;
    out = out.replace(/<p\s+class=["']section-subtitle["']>[\s\S]*?<\/p>/i, hero);
  }

  return out;
}

let scanned = 0;
let changed = 0;
for (const dirent of fs.readdirSync(path.join(ROOT, 'ru'), { recursive: true, withFileTypes: true })) {
  if (!dirent.isFile() || !dirent.name.endsWith('.html')) continue;
  const parent = dirent.parentPath || dirent.path;
  if (!parent) continue;
  const file = path.join(parent, dirent.name);
  const rel = path.relative(ROOT, file).split(path.sep).join('/');
  scanned++;
  const before = fs.readFileSync(file, 'utf8');
  const after = cleanHtml(before, rel);
  if (after !== before) { fs.writeFileSync(file, after, 'utf8'); changed++; }
}

if (scanned === 0) {
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(file);
      else if (entry.isFile() && entry.name.endsWith('.html')) {
        const rel = path.relative(ROOT, file).split(path.sep).join('/');
        scanned++;
        const before = fs.readFileSync(file, 'utf8');
        const after = cleanHtml(before, rel);
        if (after !== before) { fs.writeFileSync(file, after, 'utf8'); changed++; }
      }
    }
  };
  walk(path.join(ROOT, 'ru'));
}

